import argparse
import json
from pathlib import Path
from uuid import uuid4

from ontoproduct.agents.real_registry import build_document_registry
from ontoproduct.services.application_paths import ApplicationPaths
from ontoproduct.services.llm_service import create_llm_services
from ontoproduct.services.parser_service import ParserService
from ontoproduct.services.settings import Settings
from ontoproduct.services.workflow_runtime import WorkflowRuntime


def build_runtime(paths, llm_services):
    parser_service = ParserService(paths.uploads)

    def registry_factory(ontology):
        return build_document_registry(
            ontology, parser_service=parser_service, llm_services=llm_services
        )

    return WorkflowRuntime(paths, registry_factory=registry_factory)


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Register one product from its documents (PDF/XLSX/TXT)"
    )
    parser.add_argument("files", nargs="*", type=Path, help="Documents of one product")
    parser.add_argument(
        "--interactive", action="store_true", help="Read resume commands as JSON"
    )
    parser.add_argument(
        "--diagram", type=Path, help="Write Mermaid generated by the compiled graph"
    )
    args = parser.parse_args(argv)
    if not args.files and not args.diagram:
        parser.error("document files or --diagram is required")
    llm_services = create_llm_services(Settings.from_environment())
    runtime = build_runtime(ApplicationPaths.from_environment(), llm_services)
    try:
        if args.diagram:
            args.diagram.parent.mkdir(parents=True, exist_ok=True)
            args.diagram.write_text(runtime.compiled_diagram(), encoding="utf-8")
            print(f"Generated diagram: {args.diagram}")
            return
        session = str(uuid4())
        thread = runtime.create_case(session)
        references = [
            runtime.documents.save(session, path.name, path.read_bytes())
            for path in args.files
        ]
        print(f"Case: {thread}")
        events = runtime.start(thread, references)
        while True:
            for mode, event in events:
                if mode == "custom" and "agent" in event:
                    print(
                        f"{event['event']}: {event['agent']} {event['status']} attempt={event['attempt']}"
                    )
            snapshot = runtime.snapshot(thread)
            pending = [i for task in snapshot.tasks for i in task.interrupts]
            if not pending:
                print(
                    json.dumps(
                        {
                            "case_status": snapshot.values["case_status"],
                            "final_product": snapshot.values.get("final_product"),
                        },
                        ensure_ascii=False,
                        indent=2,
                    )
                )
                return
            payload = pending[0].value
            print("INTERRUPT " + json.dumps(payload, ensure_ascii=False))
            if args.interactive:
                while True:
                    try:
                        answer = json.loads(input("Resume JSON> "))
                        break
                    except json.JSONDecodeError:
                        print("Invalid JSON; the checkpoint is still suspended.")
            elif payload["kind"] == "error":
                answer = {"action": "STOP"}
            elif payload["review"]["can_register"]:
                answer = {"action": "APPROVE"}
            else:
                print(
                    "Human repair is required; the case stays suspended. "
                    "Rerun with --interactive or open it in the UI."
                )
                return
            print("RESUME " + json.dumps(answer, ensure_ascii=False))
            events = runtime.resume(thread, answer)
    finally:
        runtime.close()


if __name__ == "__main__":
    main()
